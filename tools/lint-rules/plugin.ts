interface SingletonsFile {
  readonly classes: ReadonlySet<string>;
  /** FQCN → property → its writers (lower-case). */
  readonly bootOnly: ReadonlyMap<string, ReadonlyMap<string, ReadonlySet<string>>>;
}

const SINGLETONS_DEFAULT = fileURLToPath(new URL("./singletons.json", import.meta.url));
const SINGLETONS_RELATIVE = "tools/lint-rules/singletons.json";
const singletonsCache = new Map<string, SingletonsFile>();

function loadSingletons(path: string): SingletonsFile {
  const cached = singletonsCache.get(path);
  if (cached !== undefined) {
    return cached;
  }
  let raw: { classes?: unknown; bootOnly?: unknown };
  try {
    raw = JSON.parse(readFileSync(path, "utf8")) as { classes?: unknown; bootOnly?: unknown };
  } catch (error) {
    throw new Error(`xaravel lint: cannot read ${path}: ${error instanceof Error ? error.message : String(error)}; regenerate it with bun run scan:singletons`);
  }
  if (raw === null || typeof raw !== "object" || !Array.isArray(raw.classes) || !Array.isArray(raw.bootOnly)) {
    throw new Error(`xaravel lint: ${path} has no "classes" and "bootOnly" arrays; regenerate it with bun run scan:singletons`);
  }
  const classes = new Set(raw.classes.filter((cls): cls is string => typeof cls === "string"));
  const bootOnly = new Map<string, Map<string, Set<string>>>();
  for (const entry of raw.bootOnly as { property?: unknown; writers?: unknown }[]) {
    if (typeof entry.property !== "string") {
      continue;
    }
    const at = entry.property.indexOf("::$");
    if (at === -1) {
      continue;
    }
    const fqcn = entry.property.slice(0, at);
    const properties = bootOnly.get(fqcn) ?? new Map<string, Set<string>>();
    properties.set(entry.property.slice(at + 3), new Set(Array.isArray(entry.writers) ? entry.writers.filter((w): w is string => typeof w === "string").map((w) => w.toLowerCase()) : []));
    bootOnly.set(fqcn, properties);
  }
  const loaded = { classes, bootOnly };
  singletonsCache.set(path, loaded);
  return loaded;
}

/** The `singletons.json` for a linted file: `<root>/tools/lint-rules/singletons.json` when it exists, else the one beside this plugin. */
export function singletonsPath(filename: string, cwd: string = process.cwd()): string {
  const path = scopePath(filename, cwd);
  let root: string;
  if (!path.startsWith("/") && !/^[A-Za-z]:\//.test(path)) {
    root = cwd.replaceAll("\\", "/").replace(/\/+$/, "");
  } else {
    const marker = ROOT_MARKER.exec(path);
    if (marker === null) {
      return SINGLETONS_DEFAULT;
    }
    root = path.slice(0, marker.index);
  }
  const candidate = `${root}/${SINGLETONS_RELATIVE}`;
  return existsSync(candidate) ? candidate : SINGLETONS_DEFAULT;
}

/** The classes a file registers: `registerClass('<FQCN>', X)` (callee `registerClass` or `<obj>.registerClass`), class name → FQCN. */
function registeredClasses(program: Node): Map<string, string> {
  const out = new Map<string, string>();
  walk(program, (node) => {
    if (node.type !== "CallExpression" || node.callee === undefined) {
      return;
    }
    const callee = unwrap(node.callee);
    if (!((callee.type === "Identifier" && callee.name === "registerClass") || memberName(callee) === "registerClass")) {
      return;
    }
    const fqcn = staticString(node.arguments?.[0]);
    const target = node.arguments?.[1] === undefined ? null : unwrap(node.arguments[1]);
    if (fqcn !== null && target?.type === "Identifier" && target.name !== undefined) {
      out.set(target.name, fqcn);
    }
  });
  return out;
}

