const noMaybePromiseReturn = rule("Disallow a public signature returning `T | Promise<T>` (AD-6).", (context) => {
  const check = (node: Node, name: string, returnType: Node | null | undefined): void => {
    const type = annotated(returnType);
    if (type === null) {
      return;
    }
    const members = unionMembers(type);
    const promises = members.filter((member) => promiseArguments(member) !== null).length;
    if (members.length > 1 && promises > 0 && promises < members.length) {
      context.report({ node: returnType!, message: MESSAGES.maybePromise(name) });
    }
  };
  /** Whether a body-bearing declaration follows bodyless overloads of the same name among `siblings`. */
  const isOverloadImplementation = (node: Node, siblings: readonly Node[], sameName: (sibling: Node) => boolean): boolean => {
    const index = siblings.indexOf(node);
    return index > 0 && siblings.slice(0, index).some(sameName);
  };
  const method = (node: Node): void => {
    if (node.kind === "constructor" || node.kind === "set" || node.accessibility === "private" || node.accessibility === "protected" || node.key?.type === "PrivateIdentifier") {
      return;
    }
    const value = node.value as Node | undefined;
    if (value === undefined) {
      return;
    }
    const name = memberKey(node) ?? "<computed>";
    if (value.body !== null && value.body !== undefined) {
      const siblings = list(node.parent?.body);
      const overloaded = isOverloadImplementation(node, siblings, (sibling) => {
        const signature = sibling.value as Node | undefined;
        return (sibling.type === "MethodDefinition" || sibling.type === "TSAbstractMethodDefinition") && memberKey(sibling) === memberKey(node) && sibling.static === node.static && signature?.type === "TSEmptyBodyFunctionExpression";
      });
      if (overloaded) {
        return;
      }
    }
    check(node, name, value.returnType);
  };
  /** A statement's function declaration, through an `export`. */
  const declared = (statement: Node): Node | null => {
    const target = statement.type === "ExportNamedDeclaration" || statement.type === "ExportDefaultDeclaration" ? statement.declaration : statement;
    return target !== undefined && target !== null && (target.type === "FunctionDeclaration" || target.type === "TSDeclareFunction") ? target : null;
  };
  /** Local names a top-level `export { name }` / `export { name as alias }` (no `from`) exports. */
  const exportedLocals = new Set<string>();
  const isExportWrapper = (node: Node | null | undefined): boolean => node?.type === "ExportNamedDeclaration" || node?.type === "ExportDefaultDeclaration";
  const exportedFunction = (node: Node): void => {
    const name = node.id?.name ?? "default";
    const wrapped = isExportWrapper(node.parent);
    if (!wrapped && !(node.parent?.type === "Program" && exportedLocals.has(name))) {
      return;
    }
    const statement = wrapped ? node.parent! : node;
    if (node.type === "FunctionDeclaration") {
      const siblings = list(statement.parent?.body);
      if (isOverloadImplementation(statement, siblings, (sibling) => declared(sibling)?.type === "TSDeclareFunction" && (declared(sibling)!.id?.name ?? "default") === name)) {
        return;
      }
    }
    check(node, name, node.returnType);
  };
  /** A function or arrow literal (through `as` / `satisfies` / parentheses), or null. */
  const functionLiteral = (node: Node | null | undefined): Node | null => {
    if (node === undefined || node === null) {
      return null;
    }
    const value = unwrap(node);
    return value.type === "ArrowFunctionExpression" || value.type === "FunctionExpression" ? value : null;
  };
  /** Whether a method signature sits inside a function's type or parameters (a callback), not an interface or type alias. */
  const inCallback = (node: Node): boolean => {
    for (let current = node.parent; current !== undefined && current !== null; current = current.parent) {
      if (isFunction(current) || current.type === "TSFunctionType" || current.type === "TSConstructorType" || current.type === "TSMethodSignature" || current.type === "TSCallSignatureDeclaration" || current.type === "TSConstructSignatureDeclaration") {
        return true;
      }
    }
    return false;
  };
  return {
    MethodDefinition: method,
    TSAbstractMethodDefinition: method,
    TSMethodSignature(node: Node): void {
      if (node.kind === "set" || inCallback(node)) {
        return;
      }
      check(node, keyName(node) ?? "<computed>", node.returnType);
    },
    FunctionDeclaration: exportedFunction,
    TSDeclareFunction: exportedFunction,
    Program(node: Node): void {
      for (const statement of list(node.body)) {
        if (statement.type === "ExportNamedDeclaration" && (statement.source === undefined || statement.source === null)) {
          for (const specifier of statement.specifiers ?? []) {
            const local = specifierName(specifier.local);
            if (local !== null) {
              exportedLocals.add(local);
            }
          }
        }
      }
    },
    // A public class field holding a function or arrow literal.
    PropertyDefinition(node: Node): void {
      if (node.accessibility === "private" || node.accessibility === "protected" || node.key?.type === "PrivateIdentifier") {
        return;
      }
      const fn = functionLiteral(isNode(node.value) ? node.value : null);
      if (fn !== null) {
        check(node, memberKey(node) ?? "<computed>", fn.returnType);
      }
    },
    // An exported `const x = <function or arrow>` (directly, or by a later `export { x }`).
    VariableDeclarator(node: Node): void {
      const declaration = node.parent;
      const name = node.id?.type === "Identifier" ? (node.id.name ?? null) : null;
      const exported = isExportWrapper(declaration?.parent) || (declaration?.parent?.type === "Program" && name !== null && exportedLocals.has(name));
      const fn = functionLiteral(node.init);
      if (exported && fn !== null) {
        check(node, name ?? "<pattern>", fn.returnType);
      }
    },
    // An interface or type-literal property whose type is a function type.
    TSPropertySignature(node: Node): void {
      const type = annotated(node.typeAnnotation);
      if (type?.type === "TSFunctionType" && !inCallback(node)) {
        check(node, keyName(node) ?? "<computed>", type.returnType);
      }
    },
  };
});

const noAsyncThenableReturn = rule("Disallow returning a thenable unawaited from an async function (AD-6).", (context) => {
  // Set by `Program`: the same-file structural thenables (a class declaring `then` or implementing `PromiseLike` /
  // `Thenable`), the file's import bindings and its own registrations (local name → FQCN: `registerClass` calls, then contract tokens).
  const structural = new Set<string>();
  let imports: ReadonlyMap<string, ImportBinding> = new Map();
  let registrations: ReadonlyMap<string, string> = new Map();
  /**
   * The thenable a type or class name refers to (`X`, or `ns.X` through `import * as ns`), or null: a same-file
   * structural thenable by its name, else a name whose import (or same-file registration) resolves to a registered
   * FQCN in `THENABLE_TYPES` (`@xaravel/contracts/async`'s list, re-exported by `./thenables`), by that FQCN.
   * Never by short name (MAINT-2026-10-19 item 7).
   */
  const thenableName = (name: Node | null | undefined): string | null => {
    if (name === undefined || name === null) {
      return null;
    }
    if (name.type === "Identifier" && name.name !== undefined) {
      // Same-file registrations first, as `localFqcn` in `./thenables` does, then the import.
      const registered = registrations.get(name.name);
      const binding = imports.get(name.name);
      if (registered !== undefined) {
        return isThenableFqcn(registered, THENABLE_TYPES) ?? (binding === undefined && structural.has(name.name) ? name.name : null);
      }
      if (binding === undefined) {
        return structural.has(name.name) ? name.name : null;
      }
      return binding.imported === null ? null : isThenableFqcn(registeredFqcn(context.filename, binding.specifier, binding.imported), THENABLE_TYPES);
    }
    const qualified = name.type === "TSQualifiedName" || (name.type === "MemberExpression" && name.computed !== true);
    const left = !qualified ? undefined : name.type === "TSQualifiedName" ? name.left : name.object;
    const right = !qualified ? undefined : name.type === "TSQualifiedName" ? name.right : name.property;
    if (left?.type !== "Identifier" || left.name === undefined || right?.type !== "Identifier" || right.name === undefined) {
      return null;
    }
    const binding = imports.get(left.name);
    return binding !== undefined && binding.imported === null ? isThenableFqcn(registeredFqcn(context.filename, binding.specifier, right.name), THENABLE_TYPES) : null;
  };
  const isThenableType = (type: Node | null | undefined): string | null => {
    const inner = annotated(type);
    if (inner === null) {
      return null;
    }
    for (const member of unionMembers(inner)) {
      const name = member.type === "TSTypeReference" ? thenableName(member.typeName) : null;
      if (name !== null) {
        return name;
      }
    }
    return null;
  };
  const isThenableNew = (node: Node | null | undefined): string | null => {
    if (node === undefined || node === null) {
      return null;
    }
    const target = unwrap(node);
    if (target.type !== "NewExpression" || target.callee === undefined) {
      return null;
    }
    return thenableName(unwrap(target.callee));
  };
  /** The thenable a `const` / `let` declaration of `name` in `fn` (outside nested functions) is annotated or initialised with. */
  const declaredThenable = (fn: Node, name: string): string | null => {
    let found: string | null = null;
    const body = fn.body;
    if (!isNode(body)) {
      return null;
    }
    walk(body, (node) => {
      if (found !== null || isFunction(node)) {
        return false;
      }
      if (node.type === "VariableDeclarator" && node.id?.type === "Identifier" && node.id.name === name && (node.parent?.kind === "const" || node.parent?.kind === "let")) {
        found = isThenableType(node.id.typeAnnotation) ?? isThenableNew(node.init);
      }
      return true;
    });
    return found;
  };
  /** The thenable a returned expression is: `new X(…)`, `<expr> as X`, or a variable declared as one. */
  const returnedThenable = (fn: Node, expression: Node): string | null => {
    let current = expression;
    for (;;) {
      if (current.type === "TSAsExpression") {
        const named = isThenableType(current.typeAnnotation);
        if (named !== null) {
          return named;
        }
      }
      if ((current.type === "ParenthesizedExpression" || current.type === "TSAsExpression" || current.type === "TSSatisfiesExpression" || current.type === "TSNonNullExpression") && inner(current) !== null) {
        current = inner(current)!;
        continue;
      }
      break;
    }
    if (current.type === "Identifier" && current.name !== undefined) {
      return declaredThenable(fn, current.name);
    }
    return isThenableNew(current);
  };
  const fn = (node: Node): void => {
    if (node.async !== true) {
      return;
    }
    const type = annotated(node.returnType);
    if (type !== null) {
      for (const member of unionMembers(type)) {
        const args = promiseArguments(member);
        const named = args === null ? null : args.map((arg) => isThenableType(arg)).find((name) => name !== null);
        if (named !== undefined && named !== null) {
          context.report({ node: node.returnType!, message: MESSAGES.asyncThenable(named) });
          break;
        }
      }
    }
    if (node.type === "ArrowFunctionExpression" && isNode(node.body) && node.body.type !== "BlockStatement") {
      const named = returnedThenable(node, node.body);
      if (named !== null) {
        context.report({ node: node.body, message: MESSAGES.asyncThenable(named) });
      }
    }
  };
  return {
    Program(node: Node): void {
      const statements = list(node.body);
      structural.clear();
      imports = importBindings(statements);
      registrations = moduleInfoOf(statements).registrations;
      walk(node, (child) => {
        if ((child.type === "ClassDeclaration" || child.type === "ClassExpression") && className(child) !== null) {
          const implementsThenable = (child.implements ?? []).some((clause) => {
            const name = entityName(inner(clause) ?? undefined);
            return name === "PromiseLike" || name === "Thenable";
          });
          const declaresThen = list(isNode(child.body) ? child.body.body : null).some((member) => member.type !== "StaticBlock" && member.static !== true && memberKey(member) === "then");
          if (implementsThenable || declaresThen) {
            structural.add(className(child)!);
          }
        }
      });
    },
    FunctionDeclaration: fn,
    FunctionExpression: fn,
    ArrowFunctionExpression: fn,
    ReturnStatement(node: Node): void {
      const owner = enclosingFunction(node);
      if (owner === null || owner.async !== true || node.argument === undefined || node.argument === null) {
        return;
      }
      const named = returnedThenable(owner, node.argument);
      if (named !== null) {
        context.report({ node: node.argument, message: MESSAGES.asyncThenable(named) });
      }
    },
  };
});

const MUTATORS: ReadonlySet<string> = new Set(["push", "unshift", "splice", "pop", "shift", "set", "add", "delete", "clear"]);

/** The registered FQCN of the class a write site belongs to, or null. */
function siteFqcn(site: WriteSite, registered: ReadonlyMap<string, string>): string | null {
  const name = className(site.cls);
  return name === null ? null : (registered.get(name) ?? null);
}

/** Visits each write in a file: `<target> = / op= …` (patterns included), `++` / `--`, `delete <target>`, with the written node. */
function writeVisitor(onWrite: (target: Node, node: Node) => void): Visitor {
  return {
    AssignmentExpression(node: Node): void {
      if (node.left !== undefined) {
        for (const target of patternTargets(node.left)) {
          onWrite(target, node);
        }
      }
    },
    UpdateExpression(node: Node): void {
      if (node.argument !== undefined && node.argument !== null) {
        onWrite(node.argument, node);
      }
    },
    UnaryExpression(node: Node): void {
      if (node.operator === "delete" && node.argument !== undefined && node.argument !== null) {
        onWrite(node.argument, node);
      }
    },
  };
}

const noSingletonFieldWrite = rule("Disallow a `this.<field>` write after construction in a singleton class (AD-5).", (context) => {
  let registered = new Map<string, string>();
  let singletons: SingletonsFile | null = null;
  const visitor = writeVisitor((target, node) => {
    if (singletons === null) {
      return;
    }
    const field = thisField(target);
    const site = field === null ? null : writeSite(node);
    if (field === null || site === null || site.at === "initialiser" || site.at === "constructor") {
      return;
    }
    const fqcn = siteFqcn(site, registered);
    if (fqcn === null || !singletons.classes.has(fqcn) || singletons.bootOnly.get(fqcn)?.has(field) === true) {
      return;
    }
    context.report({ node, message: MESSAGES.singletonWrite(field, fqcn) });
  });
  return {
    ...visitor,
    Program(node: Node): void {
      registered = registeredClasses(node);
      singletons = registered.size === 0 ? null : loadSingletons(singletonsPath(context.filename));
    },
  };
});

const noBootOnlyWrite = rule("Disallow a write to a boot-only property outside its register/boot path (AD-5).", (context) => {
  let registered = new Map<string, string>();
  let singletons: SingletonsFile | null = null;
  /** The `this.p` at the base of a `this.p`, `this.p[…]` or `this.p.x…` chain: its property name; else null. */
  const baseField = (node: Node): string | null => {
    let current = unwrap(node);
    for (;;) {
      const field = thisField(current);
      if (field !== null) {
        return field;
      }
      if (current.type !== "MemberExpression" || current.object === undefined) {
        return null;
      }
      current = unwrap(current.object);
    }
  };
  const check = (field: string | null, node: Node): void => {
    if (singletons === null || field === null) {
      return;
    }
    const site = writeSite(node);
    if (site === null || site.at === "initialiser" || site.at === "constructor") {
      return;
    }
    const fqcn = siteFqcn(site, registered);
    const writers = fqcn === null ? undefined : singletons.bootOnly.get(fqcn)?.get(field);
    if (writers === undefined || (site.at === "method" && writers.has(site.method))) {
      return;
    }
    context.report({ node, message: MESSAGES.bootOnlyWrite(`${fqcn}::$${field}`, [...writers]) });
  };
  const visitor = writeVisitor((target, node) => check(baseField(target), node));
  return {
    ...visitor,
    Program(node: Node): void {
      registered = registeredClasses(node);
      singletons = registered.size === 0 ? null : loadSingletons(singletonsPath(context.filename));
    },
    CallExpression(node: Node): void {
      const callee = node.callee === undefined ? null : unwrap(node.callee);
      const method = callee === null ? null : memberName(callee);
      if (callee === null || method === null || !MUTATORS.has(method) || callee.object === undefined) {
        return;
      }
      check(thisField(callee.object), node);
    },
  };
});

const TEST_FUNCTIONS: ReadonlySet<string> = new Set(["test", "it", "beforeEach", "afterEach", "beforeAll", "afterAll"]);
const TEST_MODIFIERS: ReadonlySet<string> = new Set(["only", "skip", "todo", "failing", "concurrent", "each", "if", "skipIf", "todoIf"]);
/** The modifiers that take arguments and return the test function: `test.each(table)(…)`, `test.if(cond)(…)`. */
const CURRIED_MODIFIERS: ReadonlySet<string> = new Set(["each", "if", "skipIf", "todoIf"]);

/** A test callee: `test`, `it` or a hook, with any `.only` / `.skip` / `.todo` / `.failing` / `.concurrent` and curried `.each(…)` / `.if(…)` / `.skipIf(…)` / `.todoIf(…)` forms. */
function isTestCallee(node: Node): boolean {
  const callee = unwrap(node);
  if (callee.type === "Identifier") {
    return callee.name !== undefined && TEST_FUNCTIONS.has(callee.name);
  }
  if (callee.type === "MemberExpression") {
    const name = memberName(callee);
    return name !== null && TEST_MODIFIERS.has(name) && callee.object !== undefined && isTestCallee(callee.object);
  }
  if (callee.type === "CallExpression" && callee.callee !== undefined) {
    const inner = unwrap(callee.callee);
    const name = memberName(inner);
    return name !== null && CURRIED_MODIFIERS.has(name) && isTestCallee(inner);
  }
  return false;
}

const noArrowTestBody = rule("Disallow arrow test bodies in a file that calls `uses()` (AD-25).", (context) => {
  let usesCalled = false;
  return {
    Program(node: Node): void {
      walk(node, (child) => {
        if (child.type === "CallExpression" && child.callee !== undefined && child.callee.type === "Identifier" && child.callee.name === "uses") {
          usesCalled = true;
        }
        return !usesCalled;
      });
    },
    CallExpression(node: Node): void {
      if (!usesCalled || node.callee === undefined || !isTestCallee(node.callee)) {
        return;
      }
      for (const argument of node.arguments ?? []) {
        if (argument.type === "ArrowFunctionExpression") {
          context.report({ node: argument, message: MESSAGES.arrowTestBody });
        }
      }
    },
  };
});

const noInjectParamMismatch = rule("Require `inject({...})` keys to be the parameter names, in order (AD-4).", (context) => {
  /** A key list, with `null` for a spread or non-static key; null when the map is not an object literal. */
  const keysOf = (map: Node | undefined): (string | null)[] | null => {
    const object = map === undefined ? null : unwrap(map);
    if (object === null || object.type !== "ObjectExpression") {
      return null;
    }
    return (object.properties ?? []).map((property) => (property.type === "Property" ? keyName(property) : null));
  };
  const NOT_LITERAL = "<not an object literal>";
  /** A parameter's name, with `null` for a destructured one; `undefined` for a TS `this` parameter. */
  const paramName = (param: Node): string | null | undefined => {
    switch (param.type) {
      case "Identifier":
        return param.name === "this" ? undefined : (param.name ?? null);
      case "AssignmentPattern":
        return param.left?.type === "Identifier" ? (param.left.name ?? null) : null;
      case "TSParameterProperty":
        return param.parameter === undefined ? null : paramName(param.parameter);
      case "RestElement":
        return param.argument?.type === "Identifier" ? (param.argument.name ?? null) : null;
      default:
        return null;
    }
  };
  const compare = (node: Node, map: Node | undefined, params: readonly Node[]): void => {
    // A map that is not an object literal cannot be checked, so it is a mismatch.
    const keys = keysOf(map) ?? [NOT_LITERAL];
    const names = params.map(paramName).filter((name): name is string | null => name !== undefined);
    const matches = keys[0] !== NOT_LITERAL && keys.length === names.length && keys.every((key, i) => key !== null && key === names[i]);
    if (!matches) {
      context.report({ node, message: MESSAGES.injectMismatch(keys.map((key) => key ?? "<spread or computed>"), names.map((name) => name ?? "<destructured>")) });
    }
  };
  return {
    Decorator(node: Node): void {
      const call = inner(node) === null ? null : unwrap(inner(node)!);
      if (call === null || call.type !== "CallExpression" || call.callee === undefined || !isInjectCallee(call.callee)) {
        return;
      }
      const target = node.parent;
      if (target === undefined || target === null) {
        return;
      }
      if (target.type === "ClassDeclaration" || target.type === "ClassExpression") {
        const members = list(isNode(target.body) ? target.body.body : null);
        const ctor = members.find((member) => member.type === "MethodDefinition" && member.kind === "constructor" && isNode(member.value) && member.value.body !== null);
        if (ctor === undefined) {
          if (target.superClass === undefined || target.superClass === null) {
            compare(node, call.arguments?.[0], []);
          }
          return;
        }
        compare(node, call.arguments?.[0], (ctor.value as Node).params ?? []);
      } else if (target.type === "MethodDefinition" || target.type === "TSAbstractMethodDefinition") {
        compare(node, call.arguments?.[0], (target.value as Node | undefined)?.params ?? []);
      }
    },
    CallExpression(node: Node): void {
      if (node.callee === undefined || !isInjectCallee(node.callee) || node.parent?.type === "Decorator" || (node.arguments?.length ?? 0) < 2) {
        return;
      }
      const fn = unwrap(node.arguments![1]!);
      if (fn.type === "FunctionExpression" || fn.type === "ArrowFunctionExpression") {
        compare(node, node.arguments![0], fn.params ?? []);
      }
    },
  };
});

const MODEL_BASES: ReadonlySet<string> = new Set(["Model", "Pivot", "MorphPivot", "Authenticatable"]);
const MODEL_CONFIG_FIELDS: ReadonlySet<string> = new Set([
  "table", "connection", "primaryKey", "keyType", "incrementing", "timestamps", "attributes", "fillable", "guarded",
  "casts", "hidden", "visible", "appends", "with", "withCount", "perPage", "dateFormat", "touches",
]);

/** `Model`, `Pivot`, `MorphPivot`, `Authenticatable` (or `<ns>.<one>`), or `mixin(<one of them>, …)`. */
function isModelBase(node: Node | null | undefined): boolean {
  if (node === undefined || node === null) {
    return false;
  }
  const base = unwrap(node);
  if (base.type === "CallExpression" && base.callee !== undefined) {
    const callee = unwrap(base.callee);
    return callee.type === "Identifier" && callee.name === "mixin" && base.arguments?.[0] !== undefined && isModelBase(base.arguments[0]);
  }
  const name = base.type === "Identifier" ? (base.name ?? null) : memberName(base);
  return name !== null && MODEL_BASES.has(name);
}

/** A constant expression: literals, `null`, a template without substitutions, `-`/`+`/`!` of one, array / object literals of them with static keys, through `as` / `satisfies` / `!` / parentheses. */
function isConstant(node: Node): boolean {
  switch (node.type) {
    case "Literal":
      // A regex literal builds a fresh object.
      return (node as { regex?: unknown }).regex === undefined || (node as { regex?: unknown }).regex === null;
    case "TemplateLiteral":
      return (node.expressions ?? []).length === 0;
    case "UnaryExpression":
      return (node.operator === "-" || node.operator === "+" || node.operator === "!") && node.argument !== undefined && node.argument !== null && isConstant(node.argument);
    case "ArrayExpression":
      return (node.elements ?? []).every((element) => element !== null && isConstant(element));
    case "ObjectExpression":
      return (node.properties ?? []).every(
        (property) => property.type === "Property" && property.kind === "init" && (property as { method?: boolean }).method !== true && keyName(property) !== null && isNode(property.value) && isConstant(property.value),
      );
    case "TSAsExpression":
    case "TSSatisfiesExpression":
    case "TSNonNullExpression":
    case "ParenthesizedExpression":
      return inner(node) !== null && isConstant(inner(node)!);
    default:
      return false;
  }
}

const noDynamicColumnDefault = rule("Require model column defaults to be constant expressions (AD-7).", (context) => ({
  PropertyDefinition(node: Node): void {
    const cls = node.parent?.parent;
    if (node.static === true || node.declare === true || !isNode(node.value) || cls === undefined || cls === null || !isModelBase(cls.superClass)) {
      return;
    }
    const name = memberKey(node);
    if (name !== null && MODEL_CONFIG_FIELDS.has(name)) {
      return;
    }
    if (!isConstant(node.value)) {
      context.report({ node: node.value, message: MESSAGES.dynamicColumnDefault(name ?? "<computed>") });
    }
  },
}));

