/** Keys that are not child nodes: back links, positions, and the token / comment lists oxlint attaches to Program. */
const NON_CHILD_KEYS: ReadonlySet<string> = new Set(["parent", "range", "loc", "start", "end", "tokens", "comments"]);

function isNode(value: unknown): value is Node {
  return typeof value === "object" && value !== null && typeof (value as { type?: unknown }).type === "string";
}

/** Calls `visit` on every node under `root` (itself included); `visit` returning false skips a node's children. */
function walk(root: Node, visit: (node: Node) => boolean | void): void {
  const stack: Node[] = [root];
  while (stack.length > 0) {
    const node = stack.pop()!;
    if (visit(node) === false) {
      continue;
    }
    for (const [key, value] of Object.entries(node)) {
      if (NON_CHILD_KEYS.has(key)) {
        continue;
      }
      if (Array.isArray(value)) {
        for (let i = value.length - 1; i >= 0; i--) {
          if (isNode(value[i])) {
            stack.push(value[i]);
          }
        }
      } else if (isNode(value)) {
        stack.push(value);
      }
    }
  }
}

const FUNCTION_TYPES: ReadonlySet<string> = new Set(["FunctionDeclaration", "FunctionExpression", "ArrowFunctionExpression", "TSEmptyBodyFunctionExpression", "TSDeclareFunction"]);

function isFunction(node: Node): boolean {
  return FUNCTION_TYPES.has(node.type);
}

/** The nearest enclosing function of `node` (not `node` itself), or null. */
function enclosingFunction(node: Node): Node | null {
  for (let current = node.parent; current !== undefined && current !== null; current = current.parent) {
    if (isFunction(current)) {
      return current;
    }
  }
  return null;
}

/** The last identifier of a type or entity name (`X`, `A.B.X`). */
function entityName(node: Node | undefined | null): string | null {
  if (node === undefined || node === null) {
    return null;
  }
  if (node.type === "Identifier") {
    return node.name ?? null;
  }
  if (node.type === "TSQualifiedName") {
    return entityName(node.right);
  }
  if (node.type === "MemberExpression") {
    return memberName(node);
  }
  return null;
}

/** A type's union members, flattened through nested unions and parenthesised types. */
function unionMembers(type: Node): Node[] {
  if (type.type === "TSParenthesizedType" && type.typeAnnotation !== undefined && type.typeAnnotation !== null) {
    return unionMembers(type.typeAnnotation);
  }
  if (type.type === "TSUnionType") {
    return (type.types ?? []).flatMap(unionMembers);
  }
  return [type];
}

/** The type a `TSTypeAnnotation` wraps (or the type itself). */
function annotated(node: Node | null | undefined): Node | null {
  if (node === undefined || node === null) {
    return null;
  }
  return node.type === "TSTypeAnnotation" ? (node.typeAnnotation ?? null) : node;
}

/** `Promise<…>` / `PromiseLike<…>`: its type argument list; else null. */
function promiseArguments(type: Node): readonly Node[] | null {
  if (type.type !== "TSTypeReference") {
    return null;
  }
  const name = entityName(type.typeName);
  return name === "Promise" || name === "PromiseLike" ? (type.typeArguments?.params ?? []) : null;
}

/** A class's name: its id, or the variable a class expression initialises. */
function className(node: Node): string | null {
  if (node.id !== undefined && node.id !== null) {
    return node.id.name ?? null;
  }
  const parent = node.parent;
  if (parent?.type === "VariableDeclarator" && parent.id?.type === "Identifier") {
    return parent.id.name ?? null;
  }
  return null;
}

/** A class member's static name (`a`, `"a"`, `["a"]`, `#a`); else null. */
function memberKey(member: Node): string | null {
  if (member.key?.type === "PrivateIdentifier") {
    return `#${member.key.name ?? ""}`;
  }
  return keyName(member);
}

/** The field a `this.<field>` member expression names (`#x` for a private name); null for another shape. */
function thisField(node: Node): string | null {
  const target = unwrap(node);
  if (target.type !== "MemberExpression" || target.object === undefined || unwrap(target.object).type !== "ThisExpression") {
    return null;
  }
  if (target.property?.type === "PrivateIdentifier") {
    return `#${target.property.name ?? ""}`;
  }
  return memberName(target);
}

/** The assignment targets of a pattern (`[a, this.b] = …`, `({ x: this.c } = …)`), or the node itself. */
function patternTargets(node: Node): Node[] {
  switch (node.type) {
    case "ArrayPattern":
      return (node.elements ?? []).flatMap((element) => (element === null ? [] : patternTargets(element)));
    case "ObjectPattern":
      return (node.properties ?? []).flatMap((property) => (property.type === "RestElement" ? patternTargets(property.argument!) : property.value !== undefined && isNode(property.value) ? patternTargets(property.value) : []));
    case "AssignmentPattern":
      return node.left === undefined ? [] : patternTargets(node.left);
    case "RestElement":
      return node.argument === undefined || node.argument === null ? [] : patternTargets(node.argument);
    default:
      return [node];
  }
}

/** Where a write inside a class runs: a field initialiser or static block, the constructor, a method (by lower-case name), or later. */
type WriteSite = { readonly cls: Node; readonly at: "initialiser" | "constructor" | "later" } | { readonly cls: Node; readonly at: "method"; readonly method: string };

/** The nearest class of `node` and where in it `node` runs; null outside any class, or under a nested non-arrow function (whose `this` is not the instance). */
function writeSite(node: Node): WriteSite | null {
  let fn: Node | null = null;
  let child: Node = node;
  for (let current = node.parent; current !== undefined && current !== null; child = current, current = current.parent) {
    if (isFunction(current)) {
      // A non-arrow function rebinds `this`, unless it is a method of the class itself.
      const owner = current.parent;
      const isMethod = (owner?.type === "MethodDefinition" || owner?.type === "TSAbstractMethodDefinition") && owner.value === current && owner.parent?.type === "ClassBody";
      if (current.type !== "ArrowFunctionExpression" && !isMethod) {
        return null;
      }
      fn ??= current;
      continue;
    }
    if (fn === null && current.type === "PropertyDefinition" && current.value === child) {
      const cls = current.parent?.parent;
      return cls === undefined || cls === null ? null : { cls, at: "initialiser" };
    }
    // A static block runs once, at class definition: construction time.
    if (fn === null && current.type === "StaticBlock") {
      const cls = current.parent?.parent;
      return cls === undefined || cls === null ? null : { cls, at: "initialiser" };
    }
    if (current.type === "ClassBody") {
      const cls = current.parent;
      if (cls === undefined || cls === null) {
        return null;
      }
      if (fn !== null && fn.parent === child && (child.type === "MethodDefinition" || child.type === "TSAbstractMethodDefinition") && child.value === fn) {
        if (child.kind === "constructor") {
          return { cls, at: "constructor" };
        }
        const name = memberKey(child);
        return name === null ? { cls, at: "later" } : { cls, at: "method", method: name.toLowerCase() };
      }
      return { cls, at: "later" };
    }
  }
  return null;
}

