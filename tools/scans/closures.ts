// The closure allowed-identifier scan (Story 3.7; the serializable-closure
// codec reads it, AD-14).
//
//   bun tools/scans/closures.ts [--check] [--root <dir>]
//       reads `conformance/upstream/` only (it runs no PHP and no container) and writes
//       `conformance/scans/allowed-identifiers.json`, `{"comment","facades","helpers"}`:
//
//       - `facades`: the short name (the last `\` segment) of every non-abstract
//         indexed class whose `extends` chain reaches
//         `Illuminate\Support\Facades\Facade`, `Facade` itself excluded. Two
//         facades with the same short name fail the run, naming both FQCNs.
//       - `helpers`: every `function <name>(` declared in a `src/` file that has
//         no `namespace` statement, outside any class, interface, trait or enum
//         body (anonymous classes included). Closures, arrow functions and
//         methods are not helpers. Deduplicated.
//
//       Both lists are sorted by UTF-16 code unit; 2-space indentation, one
//       name per line, LF-terminated.
//
//   … --check
//       builds the file in memory and compares it byte for byte with the
//       committed one: a `closures drift: <file> …` line when it differs or is
//       missing. It writes nothing.
//
// Exit codes: 0 pass, 1 any failure (nothing is written), 2 usage error.
import { compareUnits } from "../oracle/request";
import { FACADE_BASE, runScan } from "./facades";
import { buildIndex, codeIndexes, extendsChainReaches, matching, ScanError, type Index, type ParsedFile } from "./php";

export const ALLOWED_IDENTIFIERS_FILE = "conformance/scans/allowed-identifiers.json";

export const ALLOWED_IDENTIFIERS_COMMENT =
  "Generated by `bun run scan:closures` (tools/scans/closures.ts) from conformance/upstream at the Baseline Pin. Do not edit by hand: every facade short name and global helper function name, the only free identifiers the closure codec allows besides parameters and ECMAScript built-ins (Story 3.7, AD-14).";

export interface ClosuresResult {
  text: string;
  facades: string[];
  helpers: string[];
}

/** The facade short names; a duplicate short name fails, naming both FQCNs. */
export function facadeNames(index: Index): string[] {
  const byShort = new Map<string, string>();
  for (const decl of index.byFqcn.values()) {
    if (decl.kind !== "class" || decl.abstract || decl.fqcn === FACADE_BASE || !extendsChainReaches(index, decl, FACADE_BASE)) {
      continue;
    }
    const short = decl.fqcn.slice(decl.fqcn.lastIndexOf("\\") + 1);
    const other = byShort.get(short);
    if (other !== undefined) {
      const [a, b] = [other, decl.fqcn].sort(compareUnits);
      throw new ScanError(`two facades share the short name ${short}: ${a} and ${b}`);
    }
    byShort.set(short, decl.fqcn);
  }
  return [...byShort.keys()].sort(compareUnits);
}

const STATEMENT_START: ReadonlySet<string> = new Set([";", "{", "}"]);

/** The global helper functions a parsed `src/` file declares (none when it has a namespace). */
export function helperNames(parsed: ParsedFile): string[] {
  const { tokens } = parsed;
  const code = codeIndexes(tokens);
  const tok = (k: number): string => tokens[code[k]!]?.text ?? "";
  const kind = (k: number): string => tokens[code[k]!]?.kind ?? "";
  for (let k = 0; k < code.length; k++) {
    if (kind(k) === "name" && tok(k).toLowerCase() === "namespace" && (k === 0 || STATEMENT_START.has(tok(k - 1))) && (kind(k + 1) === "name" || tok(k + 1) === "{")) {
      return [];
    }
  }
  // Class-like bodies: the named declarations, plus anonymous classes.
  const ranges: [number, number][] = parsed.declarations.map((decl) => [decl.start, decl.end]);
  for (let k = 1; k < code.length; k++) {
    if (kind(k) === "name" && tok(k).toLowerCase() === "class" && tok(k - 1).toLowerCase() === "new") {
      let m = k + 1;
      while (m < code.length && tok(m) !== "{") {
        if (tok(m) === "(") {
          m = code.indexOf(matching(tokens, code[m]!, parsed.file) - 1, m);
        }
        m++;
      }
      if (m < code.length) {
        ranges.push([code[k]!, matching(tokens, code[m]!, parsed.file)]);
      }
    }
  }
  const inside = (index: number): boolean => ranges.some(([start, end]) => index >= start && index < end);
  const out: string[] = [];
  for (let k = 0; k < code.length; k++) {
    if (kind(k) !== "name" || tok(k).toLowerCase() !== "function" || inside(code[k]!)) {
      continue;
    }
    const prev = k > 0 ? tok(k - 1) : "";
    if (prev === "->" || prev === "?->" || prev === "::") {
      continue;
    }
    const m = tok(k + 1) === "&" ? k + 2 : k + 1;
    if (kind(m) === "name" && tok(m + 1) === "(") {
      out.push(tok(m));
    }
  }
  return out;
}

/** Renders `conformance/scans/allowed-identifiers.json`. */
export function renderAllowedIdentifiers(facades: readonly string[], helpers: readonly string[]): string {
  const list = (key: string, names: readonly string[], last: boolean): string[] => {
    const comma = last ? "" : ",";
    if (names.length === 0) {
      return [`  ${JSON.stringify(key)}: []${comma}`];
    }
    return [`  ${JSON.stringify(key)}: [`, ...names.map((name, i) => `    ${JSON.stringify(name)}${i < names.length - 1 ? "," : ""}`), `  ]${comma}`];
  };
  return `${["{", `  "comment": ${JSON.stringify(ALLOWED_IDENTIFIERS_COMMENT)},`, ...list("facades", facades, false), ...list("helpers", helpers, true), "}"].join("\n")}\n`;
}

/** Builds `allowed-identifiers.json` from the snapshot under `root`. */
export function buildClosures(root: string, index: Index = buildIndex(root)): ClosuresResult {
  const facades = facadeNames(index);
  const helpers = [...new Set(index.files.flatMap(helperNames))].sort(compareUnits);
  return { text: renderAllowedIdentifiers(facades, helpers), facades, helpers };
}

const USAGE = ["Usage:", "  bun tools/scans/closures.ts [--check] [--root <dir>]"].join("\n");

export function main(argv: readonly string[]): number {
  return runScan("closures", argv, USAGE, (root) => {
    const result = buildClosures(root);
    return { files: new Map([[ALLOWED_IDENTIFIERS_FILE, result.text]]), summary: `${result.facades.length} facades, ${result.helpers.length} helpers` };
  });
}

if (import.meta.main) {
  process.exit(main(process.argv.slice(2)));
}
