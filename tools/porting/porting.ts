const KIND_NAMES: Readonly<Record<SectionContentKind, string>> = { table: "table row", rule: "rule line", prose: "prose line" };

/** AD-7's Model configuration properties (spine AD-7, "Configuration properties"), without `casts`, which AD-7 makes an option pair. */
export const AD7_CONFIGURATION: ReadonlySet<string> = new Set([
  "table", "connection", "primaryKey", "keyType", "incrementing", "timestamps", "attributes", "fillable", "guarded", "hidden", "visible", "appends", "with", "withCount", "perPage", "dateFormat", "touches",
]);

/** The colliding Upstream method's new name, per configuration property (AD-7, DIV-12.4). */
export const AD7_RENAMES: Readonly<Record<string, string>> = { fillable: "setFillable", touches: "isTouching" };

export const FORM_STATIC_SPLIT = "no collision (static and instance sides)";
export const FORM_OPTION_PAIR = "option(this, name)";
export const FORM_METHOD_STATE = "method keeps the name; state behind Upstream's getters";

export interface Div12Row {
  class: string;
  name: string;
  classification: string;
  property: { declaredIn: string; static: boolean };
  method: { declaredIn: string; static: boolean };
}

export interface PortingReport {
  violations: string[];
  /** AD-26 rows present and decided. */
  constructs: number;
  /** Required sections present. */
  sections: number;
  /** DIV-12 pairs in the jsonl. */
  pairs: number;
  /** Fixture entries whose translation equals `ts`. */
  fixtures: number;
}

function message(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

/** The form of one DIV-12 pair; first match wins (PORTING.md § DIV-12 pair list). */
export function div12Form(row: Div12Row): string {
  if (row.property.static !== row.method.static) {
    return FORM_STATIC_SPLIT;
  }
  if (row.classification === "model-config" && AD7_CONFIGURATION.has(row.name)) {
    const rename = AD7_RENAMES[row.name];
    if (rename === undefined) {
      throw new Error(`no AD-7 rename for ${row.name}`);
    }
    return `property wins; method → ${rename}()`;
  }
  if (row.classification === "option-pair") {
    return FORM_OPTION_PAIR;
  }
  return FORM_METHOD_STATE;
}

const compare = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

/** The generated DIV-12 region, BEGIN and END markers included, without a trailing newline. Throws on a missing AD-7 rename. */
export function renderDiv12(rows: readonly Div12Row[]): string {
  const groups = new Map<string, { cls: string; form: string; names: string[] }>();
  for (const row of rows) {
    const form = div12Form(row);
    const key = `${row.class}\u0000${form}`;
    const group = groups.get(key) ?? { cls: row.class, form, names: [] };
    group.names.push(row.name);
    groups.set(key, group);
  }
  const sorted = [...groups.values()].sort((a, b) => compare(a.cls, b.cls) || compare(a.form, b.form));
  const lines = [DIV12_BEGIN, "", "| Class | Form | Names |", "| --- | --- | --- |"];
  for (const group of sorted) {
    const names = [...group.names].sort(compare).map((name) => `\`${name}\``);
    lines.push(`| \`${group.cls}\` | ${group.form} | ${names.join(", ")} |`);
  }
  lines.push("", `${rows.length} pairs in ${groups.size} groups.`, "", DIV12_END);
  return lines.join("\n");
}

/** Reads conformance/scans/div12-pairs.jsonl. */
export function readDiv12(root: string): Div12Row[] {
  const text = readFileSync(join(root, DIV12_FILE), "utf8");
  const rows: Div12Row[] = [];
  text.split("\n").forEach((line, index) => {
    if (line === "") {
      return;
    }
    try {
      rows.push(JSON.parse(line) as Div12Row);
    } catch (error) {
      throw new Error(`${DIV12_FILE}:${index + 1}: not valid JSON: ${message(error)}`);
    }
  });
  return rows;
}

/** Splits a Markdown table row into trimmed cells; a `|` inside backticks does not split. */
export function tableCells(line: string): string[] | null {
  const trimmed = line.trim();
  if (!trimmed.startsWith("|")) {
    return null;
  }
  const cells: string[] = [];
  let cell = "";
  let code = false;
  for (let i = 1; i < trimmed.length; i++) {
    const c = trimmed[i]!;
    if (c === "`") {
      code = !code;
    }
    if (c === "|" && !code) {
      cells.push(cell.trim());
      cell = "";
      continue;
    }
    cell += c;
  }
  if (cell.trim() !== "") {
    cells.push(cell.trim());
  }
  return cells;
}

const isSeparator = (cells: readonly string[]): boolean => cells.every((cell) => /^:?-{3,}:?$/.test(cell));

/** The first-column cells of the spine's AD-26 table, or null when it cannot be found. */
export function spineConstructs(spine: string): string[] | null {
  const lines = spine.split("\n");
  const start = lines.findIndex((line) => line.startsWith("### AD-26"));
  if (start === -1) {
    return null;
  }
  const constructs: string[] = [];
  let header = false;
  for (let i = start + 1; i < lines.length && !lines[i]!.startsWith("#"); i++) {
    const cells = tableCells(lines[i]!);
    if (cells === null) {
      if (header && constructs.length > 0) {
        break;
      }
      continue;
    }
    if (!header) {
      header = cells[0] === "PHP construct";
      continue;
    }
    if (!isSeparator(cells)) {
      constructs.push(cells[0]!);
    }
  }
  return constructs.length > 0 ? constructs : null;
}

/** The `##` headings of a Markdown text outside code fences, with 0-based line indexes. */
function headings(lines: readonly string[]): { text: string; index: number }[] {
  const found: { text: string; index: number }[] = [];
  let fence = false;
  lines.forEach((line, index) => {
    if (/^\s*(```|~~~)/.test(line)) {
      fence = !fence;
      return;
    }
    if (!fence && line.startsWith("## ")) {
      found.push({ text: line.trimEnd(), index });
    }
  });
  return found;
}

const FENCE = /^\s*(```|~~~)/;

/** The lines of the section whose heading is at `start`, up to the next `#`/`##` heading, with code-fence lines and their contents dropped. */
function sectionBody(lines: readonly string[], start: number): string[] {
  const body: string[] = [];
  let fence = false;
  for (let i = start + 1; i < lines.length; i++) {
    const line = lines[i]!;
    if (FENCE.test(line)) {
      fence = !fence;
      continue;
    }
    if (fence) {
      continue;
    }
    if (/^#{1,2} /.test(line)) {
      break;
    }
    body.push(line);
  }
  return body;
}

/** The number of lines of `kind` in a fence-free section body. */
function countKind(body: readonly string[], kind: SectionContentKind): number {
  let count = 0;
  body.forEach((line, index) => {
    const trimmed = line.trim();
    if (kind === "rule") {
      count += trimmed.startsWith("- ") ? 1 : 0;
      return;
    }
    const cells = tableCells(line);
    if (kind === "table") {
      if (cells === null || isSeparator(cells)) {
        return;
      }
      // A row followed by a separator row is its table's header.
      const next = index + 1 < body.length ? tableCells(body[index + 1]!) : null;
      count += next !== null && isSeparator(next) ? 0 : 1;
      return;
    }
    count += trimmed !== "" && cells === null && !/^([-*+]|\d+[.)])\s/.test(trimmed) && !trimmed.startsWith("#") ? 1 : 0;
  });
  return count;
}

interface Request {
  id: string;
  texts: string[];
}

function requestTexts(input: unknown): string[] {
  if (typeof input !== "object" || input === null) {
    return [];
  }
  const record = input as Record<string, unknown>;
  const texts: string[] = [];
  for (const key of ["exprs", "setup"]) {
    const value = record[key];
    if (Array.isArray(value)) {
      texts.push(...value.filter((item): item is string => typeof item === "string"));
    }
  }
  if (typeof record["template"] === "string") {
    texts.push(record["template"]);
  }
  return texts;
}

const REQUEST_SOURCE = /^(conformance\/oracle\/requests\/[^/#]+\.jsonl)#(.+)$/;
const UPSTREAM_SOURCE = /^((?:framework|ai|mcp|boost)\/[^:\s]+):([1-9]\d*)$/;

/** Whether `ts` parses as exactly one TypeScript expression; returns the problem or null. */
export function expressionParseProblem(ts: string): string | null {
  const result = parseSync("expression.ts", `(${ts});\n`, { lang: "ts" });
  if (result.errors.length > 0) {
    return result.errors.map((error) => error.message).join("; ");
  }
  interface Span {
    type: string;
    start: number;
    end: number;
    expression?: Span;
  }
  const body = (result.program as unknown as { body: Span[] }).body;
  const statement = body[0];
  const wrapper = statement?.expression;
  // `(${ts})` must be one parenthesised expression covering the whole text, and not a comma sequence.
  if (body.length !== 1 || statement!.type !== "ExpressionStatement" || wrapper === undefined || wrapper.type !== "ParenthesizedExpression" || wrapper.start !== 0 || wrapper.end !== ts.length + 2) {
    return "not exactly one expression";
  }
  if (wrapper.expression?.type === "SequenceExpression") {
    return "a comma sequence, not one expression";
  }
  return null;
}

/** Translates one fixture entry by its mode. */
export function translateEntry(mode: string, php: string): string {
  return mode === "blade" ? translateBladeTemplate(php) : translateExpression(php);
}

function checkFixture(root: string, violations: string[]): number {
  const path = join(root, FIXTURE_FILE);
  if (!existsSync(path)) {
    violations.push(`${FIXTURE_FILE}: missing`);
    return 0;
  }
  const lines = readFileSync(path, "utf8").split("\n");
  if (lines[lines.length - 1] === "") {
    lines.pop();
  }
  if (lines.length !== FIXTURE_COUNT) {
    violations.push(`${FIXTURE_FILE}: ${lines.length} line(s), expected ${FIXTURE_COUNT}`);
  }
  const requests = new Map<string, Request[] | null>();
  const loadRequests = (file: string): Request[] | null => {
    if (!requests.has(file)) {
      const full = join(root, file);
      requests.set(
        file,
        existsSync(full)
          ? readFileSync(full, "utf8")
              .split("\n")
              .filter((line) => line !== "")
              .map((line) => {
                const parsed = JSON.parse(line) as { id?: unknown; input?: unknown };
                return { id: String(parsed.id), texts: requestTexts(parsed.input) };
              })
          : null,
      );
    }
    return requests.get(file)!;
  };
  let passed = 0;
  lines.forEach((line, index) => {
    const at = `${FIXTURE_FILE}:${index + 1}`;
    let entry: unknown;
    try {
      entry = JSON.parse(line);
    } catch (error) {
      violations.push(`${at}: not valid JSON: ${message(error)}`);
      return;
    }
    if (typeof entry !== "object" || entry === null || Array.isArray(entry)) {
      violations.push(`${at}: not a JSON object`);
      return;
    }
    const record = entry as Record<string, unknown>;
    const keys = Object.keys(record).sort().join(",");
    if (keys !== "mode,php,source,ts") {
      violations.push(`${at}: fields must be exactly source, mode, php, ts; got ${keys}`);
      return;
    }
    const { source, mode, php, ts } = record;
    if (typeof source !== "string" || typeof mode !== "string" || typeof php !== "string" || typeof ts !== "string") {
      violations.push(`${at}: source, mode, php and ts must be strings`);
      return;
    }
    if (mode !== "expr" && mode !== "blade") {
      violations.push(`${at}: mode must be expr or blade, got ${JSON.stringify(mode)}`);
      return;
    }
    const request = REQUEST_SOURCE.exec(source);
    if (request !== null) {
      let found: Request[] | null;
      try {
        found = loadRequests(request[1]!);
      } catch (error) {
        violations.push(`${at}: ${request[1]}: unreadable: ${message(error)}`);
        found = [];
      }
      if (found === null) {
        violations.push(`${at}: source file ${request[1]} does not exist`);
      } else if (!found.some((candidate) => candidate.id === request[2] && candidate.texts.some((text) => text.includes(php)))) {
        violations.push(`${at}: php not found at ${source}`);
      }
    } else if (UPSTREAM_SOURCE.exec(source) === null) {
      violations.push(`${at}: source must be <request file>#<request id> or <upstream path>:<line>, got ${JSON.stringify(source)}`);
    }
    if (mode === "expr") {
      const problem = expressionParseProblem(ts);
      if (problem !== null) {
        violations.push(`${at}: ts does not parse: ${problem}`);
      }
    }
    let out: string;
    try {
      out = translateEntry(mode, php);
    } catch (error) {
      out = error instanceof UntranslatableExpression ? `UntranslatableExpression: ${error.message}` : `error: ${message(error)}`;
      violations.push(`${at}: translation differs: expected ${JSON.stringify(ts)}, got ${JSON.stringify(out)}`);
      return;
    }
    if (out !== ts) {
      violations.push(`${at}: translation differs: expected ${JSON.stringify(ts)}, got ${JSON.stringify(out)}`);
      return;
    }
    passed++;
  });
  return passed;
}

/** The 0-based [begin, end] line indexes of the generated region, or null when a marker is missing. */
function regionBounds(lines: readonly string[]): [number, number] | null {
  const begin = lines.indexOf(DIV12_BEGIN);
  const end = lines.indexOf(DIV12_END, begin + 1);
  return begin === -1 || end === -1 ? null : [begin, end];
}

/** Checks `PORTING.md`, the spine's AD-26 rows, the DIV-12 region and the expression fixture under `root`. */
export function checkPorting(root: string): PortingReport {
  const violations: string[] = [];
  let constructs = 0;
  let sections = 0;
  let pairs = 0;

  let spineRows: string[] | null = null;
  try {
    spineRows = spineConstructs(readFileSync(join(root, SPINE_FILE), "utf8"));
  } catch {
    spineRows = null;
  }
  if (spineRows === null) {
    violations.push(`${SPINE_FILE}: AD-26 construct table not found`);
  }

  let rendered: string | null = null;
  try {
    const rows = readDiv12(root);
    pairs = rows.length;
    rendered = renderDiv12(rows);
  } catch (error) {
    violations.push(`${DIV12_FILE}: ${message(error)}`);
  }

  const portingPath = join(root, PORTING_FILE);
  if (!existsSync(portingPath)) {
    violations.push(`${PORTING_FILE}: missing`);
  } else {
    const lines = readFileSync(portingPath, "utf8").split("\n");
    const found = headings(lines);
    let cursor = 0;
    const located = new Map<string, number>();
    for (const section of REQUIRED_SECTIONS) {
      const at = found.findIndex((heading, index) => index >= cursor && heading.text === section);
      if (at === -1) {
        violations.push(`${PORTING_FILE}: missing section "${section}"`);
        continue;
      }
      located.set(section, found[at]!.index);
      cursor = at + 1;
      sections++;
    }
    const required: ReadonlySet<string> = new Set(REQUIRED_SECTIONS);
    const counted = new Set<string>();
    for (const heading of found) {
      if (!required.has(heading.text)) {
        violations.push(`${PORTING_FILE}: unexpected section "${heading.text}"`);
      } else if (counted.has(heading.text)) {
        violations.push(`${PORTING_FILE}: duplicate section "${heading.text}"`);
      }
      counted.add(heading.text);
    }

    // Section content: a line of the section's kind and its anchor, outside code fences.
    for (const [section, rule] of Object.entries(SECTION_CONTENT)) {
      const start = located.get(section);
      if (start === undefined) {
        continue;
      }
      const body = sectionBody(lines, start);
      if (countKind(body, rule.kind) === 0) {
        violations.push(`${PORTING_FILE}: section "${section}" has no ${KIND_NAMES[rule.kind]}`);
      }
      if (!body.join("\n").includes(rule.anchor)) {
        violations.push(`${PORTING_FILE}: section "${section}" lacks "${rule.anchor}"`);
      }
    }

    // The construct table: rows from the AD-26 section to the next heading.
    const sectionStart = located.get(REQUIRED_SECTIONS[0]);
    if (spineRows !== null) {
      const rows = new Map<string, string>();
      const inSpine: ReadonlySet<string> = new Set(spineRows);
      if (sectionStart !== undefined) {
        for (let i = sectionStart + 1; i < lines.length && !/^#{1,2} /.test(lines[i]!); i++) {
          const cells = tableCells(lines[i]!);
          if (cells === null || isSeparator(cells) || cells[0] === "PHP construct") {
            continue;
          }
          const construct = cells[0]!;
          if (rows.has(construct)) {
            violations.push(`${PORTING_FILE}: AD-26 row "${construct}" duplicate`);
            continue;
          }
          if (!inSpine.has(construct)) {
            violations.push(`${PORTING_FILE}: AD-26 row "${construct}" not in the spine`);
          }
          if (cells.length < 3 || cells[1] === "") {
            violations.push(`${PORTING_FILE}: AD-26 row "${construct}" has no Xaravel form`);
          }
          rows.set(construct, cells[cells.length - 1]!);
        }
      }
      for (const construct of spineRows) {
        const status = rows.get(construct);
        if (status === undefined) {
          violations.push(`${PORTING_FILE}: AD-26 row "${construct}" missing`);
        } else if (status !== "decided") {
          violations.push(`${PORTING_FILE}: AD-26 row "${construct}" not decided (${status})`);
        } else {
          constructs++;
        }
      }
    }

    if (rendered !== null) {
      const bounds = regionBounds(lines);
      const drift = (lineIndex: number): void => {
        violations.push(`${PORTING_FILE}: div12-pairs region drift at line ${lineIndex + 1}; run bun run porting:generate`);
      };
      if (bounds === null) {
        const begin = lines.indexOf(DIV12_BEGIN);
        drift(begin !== -1 ? begin : (located.get("## DIV-12 pair list") ?? lines.length - 1));
      } else {
        const expected = rendered.split("\n");
        const actual = lines.slice(bounds[0], bounds[1] + 1);
        const length = Math.max(expected.length, actual.length);
        for (let i = 0; i < length; i++) {
          if (expected[i] !== actual[i]) {
            drift(bounds[0] + i);
            break;
          }
        }
      }
    }
  }

  const fixtures = checkFixture(root, violations);
  return { violations, constructs, sections, pairs, fixtures };
}

/** Rewrites the DIV-12 region of `PORTING.md` in place; returns whether it changed. Throws when the file or a marker is missing. */
export function generatePorting(root: string): { changed: boolean; pairs: number } {
  const path = join(root, PORTING_FILE);
  if (!existsSync(path)) {
    throw new Error(`${PORTING_FILE}: missing`);
  }
  const text = readFileSync(path, "utf8");
  const lines = text.split("\n");
  const bounds = regionBounds(lines);
  if (bounds === null) {
    throw new Error(`${PORTING_FILE}: the div12-pairs markers are missing (${DIV12_BEGIN} ... ${DIV12_END})`);
  }
  const rows = readDiv12(root);
  const region = renderDiv12(rows).split("\n");
  const next = [...lines.slice(0, bounds[0]), ...region, ...lines.slice(bounds[1] + 1)].join("\n");
  if (next !== text) {
    writeFileSync(path, next);
  }
  return { changed: next !== text, pairs: rows.length };
}

const USAGE = "Usage: bun tools/porting/porting.ts check|generate [--root <dir>]";

function parseArgs(argv: readonly string[]): { command: "check" | "generate"; root: string } {
  const command = argv[0];
  if (command !== "check" && command !== "generate") {
    throw new UsageError(command === undefined ? "Missing subcommand: check or generate" : `Unknown subcommand: ${command}`);
  }
  const rest = argv.slice(1);
  let root = resolve(import.meta.dir, "..", "..");
  for (let i = 0; i < rest.length; i++) {
    const arg = rest[i]!;
    if (arg !== "--root") {
      throw new UsageError(`Unknown argument: ${arg}`);
    }
    const value = rest[++i];
    if (value === undefined || value === "" || value.startsWith("--")) {
      throw new UsageError(`${arg} needs a value`);
    }
    root = resolve(value);
  }
  return { command, root };
}

export function main(argv: readonly string[]): number {
  const subcommand = argv[0] === "generate" ? "generate" : "check";
  try {
    const { command, root } = parseArgs(argv);
    if (command === "generate") {
      const result = generatePorting(root);
      process.stdout.write(`${PORTING_FILE}: div12-pairs region ${result.changed ? "regenerated" : "up to date"} (${result.pairs} pairs).\n`);
      return 0;
    }
    const report = checkPorting(root);
    if (report.violations.length > 0) {
      process.stderr.write(report.violations.map((violation) => `${violation}\n`).join(""));
      return 1;
    }
    process.stdout.write(
      `PORTING OK: ${report.constructs} construct row(s) decided, ${report.sections} section(s), ${report.pairs} DIV-12 pair(s), ${report.fixtures} fixture translation(s).\n`,
    );
    return 0;
  } catch (error) {
    if (error instanceof UsageError) {
      process.stderr.write(`${error.message}\n${USAGE}\n`);
      return 2;
    }
    process.stderr.write(`PORTING ${subcommand} failed: ${message(error)}\n`);
    return 1;
  }
}

if (import.meta.main) {
  process.exit(main(process.argv.slice(2)));
}
