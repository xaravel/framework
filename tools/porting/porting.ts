// The `PORTING.md` gate (Story 8.2; FR-8, AD-26; docs/ops/porting.md documents
// the rules and how to revise them).
//
//   bun tools/porting/porting.ts check [--root <dir>]
//       (`bun run porting:check`) checks the root `PORTING.md` against the
//       spine and the committed scans, and the mechanical expression rule
//       against its fixture. Prints one violation per line on stderr and
//       exits 1, or prints `PORTING OK: <c> construct row(s) decided, <s>
//       section(s), <r> DIV-12 pair(s), <f> fixture translation(s).`
//   bun tools/porting/porting.ts generate [--root <dir>]
//       (`bun run porting:generate`) rewrites the generated DIV-12 region of
//       `PORTING.md` from conformance/scans/div12-pairs.jsonl; the rest of the
//       file stays byte-identical.
//
// Rules (one violation per problem):
//   - `PORTING.md` exists (`PORTING.md: missing`).
//   - Its `##` headings, outside code fences, are exactly REQUIRED_SECTIONS in
//     that order (`PORTING.md: missing section "## <name>"`, or
//     `PORTING.md: unexpected section "## <name>"`).
//   - SECTION_CONTENT: each of `## Idiom table`, `## Test-adaptation rules`,
//     `## Mechanical expression rule`, `## By-reference parameters`,
//     `## Exceptions` and `## Scalar coercion (AD-9)` that is present holds, from its heading to the next
//     `#`/`##` heading and outside code fences, at least one line of its kind
//     (a table data row, a `- ` rule line, or a prose line) and its anchor
//     phrase (`PORTING.md: section "<h>" has no <table row|rule line|prose
//     line>`, `PORTING.md: section "<h>" lacks "<anchor>"`). A missing section
//     is reported only as `missing section`.
//   - Every row of the spine's AD-26 table (the first cell of each row under
//     `### AD-26`) has a row in the `## Construct mapping (AD-26)` table with a
//     character-identical first cell and the last cell `decided`
//     (`PORTING.md: AD-26 row "<construct>" missing` / `... not decided
//     (<status>)`). A spine without the table is `<spine>: AD-26 construct
//     table not found`.
//   - The region between DIV12_BEGIN and DIV12_END equals `renderDiv12` of
//     conformance/scans/div12-pairs.jsonl (`PORTING.md: div12-pairs region
//     drift at line <n>; run bun run porting:generate`, naming the first
//     differing line, or the BEGIN line when a marker is missing).
//   - conformance/porting/expressions.jsonl has exactly 20 lines of
//     `{"source","mode","php","ts"}`; `mode` is `expr` or `blade`; a
//     `<request file>#<request id>` source names a committed Oracle request
//     whose `exprs`, `setup` or `template` contains `php` verbatim (an
//     `<upstream path>:<line>` source is checked for shape only: the `check`
//     job does not sync conformance/upstream/, and the Xaravel Test checks it
//     where the snapshot is synced); an expr-mode `ts` parses as one
//     TypeScript expression (oxc-parser); and the translator's output equals
//     `ts` (`<file>:<line>: translation differs: expected <ts>, got <out>`,
//     both JSON-quoted).
//
// Exit codes: 0 pass, 1 violations or any failure (fail closed), 2 usage error.
