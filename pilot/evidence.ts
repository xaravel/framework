// pilot/porting: Story 8.7 pilot tooling, never merged.
//
// Writes pilot/evidence.md, Upstream evidence the Fidelity Review prompt does
// not carry on its own, copied verbatim from tracked or synced files:
//
//   1. For every sampled provider row, the `#[DataProvider('<p>')]` provider
//      method of its Upstream file (`conformance/upstream/...`), with its line
//      range. The prompt's Inventory context holds only the test method lines.
//   2. For every sampled Test ID with a committed Oracle request, the request
//      file, whether its fixture exists, and its `conformance/oracle/nondeterminism.jsonl`
//      line when it has one (a nondeterministic request has no fixture by design).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { FIXTURES_DIR } from "../tools/oracle/fixtures";
import { committedRequests } from "../tools/oracle/verify";

const root = resolve(import.meta.dir, "..");
const sample = JSON.parse(readFileSync(join(import.meta.dir, "sample.json"), "utf8")) as { strata: { ids: string[] }[] };
const ids = sample.strata.flatMap((stratum) => stratum.ids);
const out: string[] = [
  "<!-- pilot/porting: Story 8.7 pilot translation, never merged -->",
  "# Pilot evidence (generated by pilot/evidence.ts)",
  "",
  "Copied verbatim from the Upstream source and the committed Oracle files, for the Fidelity Review of the pilot translations.",
  "",
  "## Data providers of the sampled provider rows",
  "",
];

const providers = new Map<string, { file: string; tests: Set<string> }>();
for (const id of ids.filter((id) => id.includes("#"))) {
  const [cls, method] = id.split("#")[0]!.split("\\").at(-1)!.split("::") as [string, string];
  const file = `framework/tests/Support/${cls}.php`;
  const lines = readFileSync(join(root, "conformance", "upstream", file), "utf8").split("\n");
  const at = lines.findIndex((line) => new RegExp(`function ${method}\\(`).test(line));
  let name: string | null = null;
  for (let i = at - 1; i >= 0 && i >= at - 5; i--) {
    const match = /#\[DataProvider\('([A-Za-z0-9_]+)'\)\]/.exec(lines[i]!);
    if (match !== null) {
      name = match[1]!;
      break;
    }
  }
  if (name === null) {
    throw new Error(`${id}: no #[DataProvider] above ${method}`);
  }
  const key = `${file}::${name}`;
  const entry = providers.get(key) ?? { file, tests: new Set<string>() };
  entry.tests.add(`${method} (${id.split("#")[1]})`);
  providers.set(key, entry);
}
for (const [key, { file, tests }] of providers) {
  const name = key.split("::")[1]!;
  const lines = readFileSync(join(root, "conformance", "upstream", file), "utf8").split("\n");
  const start = lines.findIndex((line) => new RegExp(`function ${name}\\(`).test(line));
  let end = start;
  let depth = 0;
  let opened = false;
  for (let i = start; i < lines.length; i++) {
    for (const char of lines[i]!) {
      if (char === "{") {
        depth++;
        opened = true;
      } else if (char === "}") {
        depth--;
      }
    }
    if (opened && depth === 0) {
      end = i;
      break;
    }
  }
  out.push(`### \`${name}\` (${file}:${start + 1}-${end + 1})`, "", `Used by the sampled rows: ${[...tests].sort().join(", ")}.`, "", "```php", ...lines.slice(start, end + 1), "```", "");
}

out.push("## Committed Oracle requests of the sampled Test IDs", "");
const nondeterminism = new Map<string, string>();
for (const line of readFileSync(join(root, "conformance", "oracle", "nondeterminism.jsonl"), "utf8").split("\n")) {
  if (line.trim() !== "") {
    nondeterminism.set((JSON.parse(line) as { sha256: string }).sha256, line);
  }
}
const wanted = new Set(ids);
let any = false;
for (const [sha256, request] of committedRequests(root).requests) {
  if (!wanted.has(request.id)) {
    continue;
  }
  any = true;
  const fixture = `${FIXTURES_DIR}/${request.component}/${sha256}.json`;
  const exists = existsSync(join(root, fixture));
  out.push(`- \`${request.id}\`: request \`${sha256}\` in \`${request.file}\`; fixture \`${fixture}\` ${exists ? "exists" : "does not exist"}.`);
  const nd = nondeterminism.get(sha256);
  if (nd !== undefined) {
    out.push(`  It is listed in \`conformance/oracle/nondeterminism.jsonl\`, so the Oracle records no fixture for it and the pilot relies on none: \`${nd}\``);
  }
}
if (!any) {
  out.push("None.");
}
writeFileSync(join(import.meta.dir, "evidence.md"), `${out.join("\n")}\n`);
process.stdout.write(`wrote pilot/evidence.md: ${providers.size} providers\n`);
