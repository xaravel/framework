// pilot/porting: Story 8.7 pilot tooling, never merged.
//
// Generates the declaration-only modules the pilot translations type-check
// against (ESC-8.7-1 item 1). They declare and implement nothing:
//
//   types/collections.d.ts      @xaravel/collections, from conformance/api-surface/collections.jsonl
//   types/support.d.ts          @xaravel/support, from conformance/api-surface/support.jsonl (facades excluded)
//   types/support-facades.d.ts  @xaravel/support/facades, the Illuminate\Support\Facades\* rows of support.jsonl
//   types/contracts/<ns>.d.ts   @xaravel/contracts/<ns>, from conformance/api-surface/contracts.jsonl
//                               (each interface is an interface plus a same-named token value)
//   types/database.d.ts         @xaravel/database: Eloquent Model only, the one class from another
//                               Component the pilot's Upstream files import
//   types/runtime.d.ts          @xaravel/runtime and @xaravel/runtime/php: the helpers PORTING.md's idiom
//                               table and mechanical rule name, plus the global PHP classes the four
//                               pilot Upstream files import with `use` and the bare functions they call
//                               that no api-surface row declares
//
// Every return and parameter type is `any`: api-surface records `returns` as
// null for almost every row. A class with `__call`/`__get` gets an instance
// index signature, one with `__callStatic` a static one. Classes whose name
// ends in `Exception` extend `Error` (PORTING.md § Exceptions).
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const out = join(import.meta.dir, "types");

interface Param {
  name: string;
  optional: boolean;
  variadic: boolean;
}
interface Row {
  fqcn: string;
  kind: string;
  member: string | null;
  static?: boolean;
  parameters?: Param[];
}

const RESERVED = new Set(
  "break case catch class const continue debugger default delete do else enum export extends false finally for function if import in instanceof new null return super switch this throw true try typeof var void while with yield let static implements interface package private protected public await arguments eval".split(" "),
);

function rows(file: string): Row[] {
  return readFileSync(join(root, "conformance", "api-surface", file), "utf8")
    .split("\n")
    .filter((line) => line.trim() !== "")
    .map((line) => JSON.parse(line) as Row);
}

function shortName(fqcn: string): string {
  return fqcn.split("\\").at(-1)!;
}

function params(list: readonly Param[]): string {
  let optional = false;
  return list
    .map((p) => {
      const name = RESERVED.has(p.name) ? `_${p.name}` : p.name;
      if (p.variadic) {
        return `...${name}: any[]`;
      }
      optional ||= p.optional;
      return `${name}${optional ? "?" : ""}: any`;
    })
    .join(", ");
}

function memberKey(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

/** The declarations of `all`'s classes, traits, enums, interfaces and functions, keyed by short name; the first of two same-named wins. */
function emit(all: readonly Row[], header: string, keep: (fqcn: string) => boolean): string {
  const lines: string[] = [`// pilot/porting: Story 8.7 pilot translation, never merged`, `// Generated by pilot/gen-dts.ts from ${header}. Declarations only.`, ""];
  const byFqcn = new Map<string, Row[]>();
  const decls: Row[] = [];
  for (const row of all) {
    if (!keep(row.fqcn)) {
      continue;
    }
    if (row.member === null) {
      decls.push(row);
    } else {
      byFqcn.set(row.fqcn, [...(byFqcn.get(row.fqcn) ?? []), row]);
    }
  }
  const seen = new Set<string>();
  for (const decl of decls) {
    const name = shortName(decl.fqcn);
    if (seen.has(name)) {
      lines.push(`// skipped ${decl.fqcn}: short name ${name} already declared`, "");
      continue;
    }
    seen.add(name);
    if (decl.kind === "function") {
      lines.push(`export declare function ${RESERVED.has(name) ? `_${name}` : name}(...args: any[]): any;`, "");
      continue;
    }
    const members = byFqcn.get(decl.fqcn) ?? [];
    const methods = members.filter((m) => m.kind === "method");
    const body: string[] = [];
    if (methods.some((m) => !m.static && (m.member === "__call" || m.member === "__get"))) {
      body.push("  [key: string]: any;");
    }
    if (methods.some((m) => m.static && m.member === "__callStatic")) {
      body.push("  static [key: string]: any;");
    }
    const names = new Set<string>();
    for (const m of methods) {
      if (m.member === "__construct") {
        body.push(`  constructor(${params(m.parameters ?? [])});`);
        continue;
      }
      names.add(`${m.static ? "s" : "i"}:${m.member}`);
      body.push(`  ${m.static ? "static " : ""}${memberKey(m.member!)}(${params(m.parameters ?? [])}): any;`);
    }
    for (const m of members.filter((r) => r.kind !== "method")) {
      const isStatic = m.kind === "constant" || m.kind === "case" || m.static === true;
      if (names.has(`${isStatic ? "s" : "i"}:${m.member}`)) {
        continue;
      }
      body.push(`  ${isStatic ? "static " : ""}${m.kind === "constant" || m.kind === "case" ? "readonly " : ""}${memberKey(m.member!)}: any;`);
    }
    if (decl.kind === "interface") {
      lines.push(`export interface ${name} {`, ...body.filter((l) => !l.includes("static ") && !l.includes("constructor(")), `}`);
      lines.push(`export declare const ${name}: abstract new (...args: any[]) => ${name};`, "");
      continue;
    }
    const ext = name.endsWith("Exception") ? " extends Error" : "";
    lines.push(`export declare ${decl.kind === "class" ? "" : "abstract "}class ${name}${ext} {`, ...body, `}`, "");
  }
  return `${lines.join("\n")}\n`;
}

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, "contracts"), { recursive: true });

const collections = rows("collections.jsonl");
const support = rows("support.jsonl");
const FACADES = "Illuminate\\Support\\Facades\\";
writeFileSync(join(out, "collections.d.ts"), emit(collections, "conformance/api-surface/collections.jsonl", () => true));
writeFileSync(join(out, "support.d.ts"), emit(support, "conformance/api-surface/support.jsonl", (fqcn) => !fqcn.startsWith(FACADES)));
writeFileSync(join(out, "support-facades.d.ts"), emit(support, "conformance/api-surface/support.jsonl (facades)", (fqcn) => fqcn.startsWith(FACADES)));

// @xaravel/contracts/<ns>: `Illuminate\Contracts\Support\Arrayable` → contracts/support.d.ts.
const contracts = rows("contracts.jsonl");
const namespaces = new Set(contracts.map((row) => row.fqcn.split("\\").slice(2, -1).join("/")).filter((ns) => ns !== ""));
for (const ns of namespaces) {
  const prefix = `Illuminate\\Contracts\\${ns.replaceAll("/", "\\")}\\`;
  const file = ns.replace(/([a-z])([A-Z])/g, "$1-$2").toLowerCase().replaceAll("/", "-");
  writeFileSync(join(out, "contracts", `${file}.d.ts`), emit(contracts, `conformance/api-surface/contracts.jsonl (${prefix})`, (fqcn) => fqcn.startsWith(prefix) && !fqcn.slice(prefix.length).includes("\\")));
}

// @xaravel/database: only the classes from another Component that the pilot's Upstream files import
// (`use Illuminate\Database\Eloquent\Model;` in SupportCollectionTest), from conformance/api-surface/database.jsonl.
const OTHER_COMPONENT_CLASSES = new Set(["Illuminate\\Database\\Eloquent\\Model"]);
writeFileSync(join(out, "database.d.ts"), emit(rows("database.jsonl"), "conformance/api-surface/database.jsonl (Eloquent Model only)", (fqcn) => OTHER_COMPONENT_CLASSES.has(fqcn)));

// @xaravel/runtime(/php).
const HELPERS = ["looseEquals", "spaceship", "isNumeric", "toInt", "toFloat", "toPhpString", "toBool", "valueCopy", "phpSerialize", "phpUnserialize", "jsonEncode", "jsonDecode", "fqcn", "registerClass", "float", "isFloat", "normalizeNull"];
const PILOT_FILES = ["SupportCollectionTest", "SupportArrTest", "SupportStrTest", "SupportStringableTest"].map((name) => readFileSync(join(root, "conformance", "upstream", "framework", "tests", "Support", `${name}.php`), "utf8"));
const globals = new Set<string>();
for (const text of PILOT_FILES) {
  for (const match of text.matchAll(/^use ([A-Za-z_][A-Za-z0-9_]*);$/gm)) {
    if (match[1] !== "Mockery") {
      globals.add(match[1]!);
    }
  }
}
const declared = new Set([...collections, ...support].filter((row) => row.kind === "function").map((row) => shortName(row.fqcn)));
const KEYWORDS = new Set("array isset empty unset list fn function if elseif foreach for while switch match return new echo print exit die include require catch use static self parent and or xor clone yield throw".split(" "));
const builtins = new Set<string>();
for (const raw of PILOT_FILES) {
  // Strings and comments out, so words inside them are not read as calls.
  const text = raw.replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*|#[^\[\n][^\n]*|'(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*"/g, " ");
  for (const match of text.matchAll(/(?<![$>:\\\w])([a-z_][a-z0-9_]*)\s*\(/g)) {
    const name = match[1]!;
    const before = text.slice(Math.max(0, match.index! - 9), match.index!);
    if (KEYWORDS.has(name) || RESERVED.has(name) || declared.has(name) || /function\s+$/.test(before)) {
      continue;
    }
    builtins.add(name);
  }
}
const runtime = [
  "// pilot/porting: Story 8.7 pilot translation, never merged",
  "// Generated by pilot/gen-dts.ts: the helpers PORTING.md names, the global PHP classes the pilot's Upstream files `use`, and the builtin functions they call. Declarations only.",
  "",
  "export declare class PhpArray<K = any, V = any> { constructor(entries?: Iterable<readonly [K, V]>); [key: string]: any; }",
  "export declare class Ref<T = any> { constructor(value?: T); value: T; }",
  ...HELPERS.map((name) => `export declare function ${name}(...args: any[]): any;`),
  ...[...globals].sort().map((name) => (name.endsWith("Exception") || name.endsWith("Error") || name === "Exception" ? `export declare class ${name} extends Error { constructor(...args: any[]); [key: string]: any; }` : `export declare class ${name} { constructor(...args: any[]); [key: string]: any; static [key: string]: any; }`)),
  ...[...builtins].sort().filter((name) => !HELPERS.includes(name)).map((name) => `export declare function ${name}(...args: any[]): any;`),
  "",
];
writeFileSync(join(out, "runtime.d.ts"), runtime.join("\n"));
process.stdout.write(`generated ${out}: collections, support, support-facades, ${namespaces.size} contracts modules, runtime (${globals.size} classes, ${builtins.size} builtins)\n`);
